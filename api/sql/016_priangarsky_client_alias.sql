-- Соответствие названий: «Приангарский ЛПК ООО» = «Приангарский
-- Лесоперерабатывающий Комплекс ООО».
--
-- Подтверждено Николаем 31.07.2026: это одна фирма. В платежах она приходит
-- сокращённо, в сделках записана полностью, и программа считала их разными
-- конторами. Из-за этого платёж на 3 657 958,44 ₽ со ссылкой «СП №55» не
-- попадал даже в список кандидатов на привязку к своей же спецификации.
--
-- Автоматически спецификация 55 всё равно не закрывается: по ней оплачено
-- 5 249 545,87 ₽, а в базе лежит только 3 657 958,44 ₽ — остальное пришло до
-- 2026 года, за границей загруженного периода. Правила 014 и 015 требуют
-- точной суммы и такую сделку не трогают. Это соответствие даёт лишь одно:
-- платёж становится виден в подвале сделки и доступен для ручной привязки.
--
-- Записано как подтверждённое, а не как предложение: решение принял владелец
-- данных, а не программа.

insert into payment_client_aliases (
    payment_name, counterparty_id, status, evidence_type, evidence_count
)
select
    'Приангарский ЛПК ООО',
    c.id,
    'confirmed',
    'confirmed_by_owner',
    1
from counterparties c
where c.name = 'Приангарский Лесоперерабатывающий Комплекс ООО'
  and not exists (
      select 1 from payment_client_aliases existing
      where existing.payment_name = 'Приангарский ЛПК ООО'
        and existing.counterparty_id = c.id
  );
