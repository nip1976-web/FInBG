-- Приводит паспорт сделки в соответствие с её же данными.
--
-- Откуда расхождение. 30.07.2026 у сделки Новоторжского ЛПК исправили номер
-- счёта: 3229 принадлежал Алтай-Форесту, верный номер 3122. Номер поправили,
-- а паспорт — строку, по которой сделка опознаётся при перезаливке, —
-- пересчитать забыли. В нём так и остался 3229.
--
-- Пока файл не перезаливали, это ничем себя не проявляло. При первой же
-- перезаливке сделка не опозналась бы: в файле теперь 3122, в паспорте 3229,
-- и привязанный платёж на 11 000 ₽ остался бы на осиротевшей записи.
-- Нашла это проверка вхолостую 07.08.2026.
--
-- Правило общее, а не про одну сделку: паспорт обязан совпадать с тем, что
-- даёт формула по данным сделки. Любая будущая правка номера, даты или вида
-- документа снова разойдётся с паспортом, и этот запрос её вылечит.
--
-- Исключение — дубли строк файла с суффиксом «-dubl-<id>». Там расхождение
-- намеренное: их паспорт занят более ранней сделкой, и перезаливка обходит их
-- стороной. Приведи их «в соответствие» — и они столкнутся с оригиналом.

begin;

update deals d
set deal_number = buyers_deal_number(
        d.customer_id,
        d.original_document_type,
        d.original_document_number,
        d.source_payload->>'documentDate',
        d.source_payload->>'paymentDate',
        d.source_payload->>'dealAmount'
    ),
    updated_at = now()
where d.source = 'buyers'
  and d.deal_number not like '%-dubl-%'
  and d.deal_number <> buyers_deal_number(
        d.customer_id,
        d.original_document_type,
        d.original_document_number,
        d.source_payload->>'documentDate',
        d.source_payload->>'paymentDate',
        d.source_payload->>'dealAmount'
    );

commit;
