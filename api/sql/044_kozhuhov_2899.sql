-- ИП Кожухов: платёж #2523 на 63 000 ₽ — это счёт 2899, а не 2893.
-- Решение Николая 14.09.2026.
--
-- В один день пришли две платёжки, 63 000 и 56 550, и обе назвали счёт 2893.
-- Счёт 2893 — на 56 550, а счёт 2899 от 06.11.2025 — ровно на 63 000 и не
-- оплачен. Вместе платёжки закрывают оба счёта.
--
-- Пишем в таблицу ручного деления, хотя счёт здесь один: правило то же —
-- человек назвал счёт и сумму, программа проверила, что сумма сходится с
-- платежом.

insert into payment_invoice_splits (payment_id, bitrix_invoice_id, amount_rub, reason)
values (2523, 2899, 63000.00,
        'ИП Кожухов: в назначении назван счёт 2893, но 2893 — на 56 550, а этот платёж равен счёту 2899. Николай, 14.09.2026')
on conflict (payment_id, bitrix_invoice_id) do update
    set amount_rub = excluded.amount_rub,
        reason     = excluded.reason;
