-- Убирает из базы внутренние переводы и всё, что в наличных не основная
-- деятельность.
--
-- Решение Николая 07.08.2026: в поступлениях нужны только продажи. Снятие
-- своих денег с расчётного счёта в кассу — «ВП: с р/сч» — выручкой не является
-- и считается дважды: сначала как поступление от клиента на счёт, потом ещё раз
-- как приход в кассу. Из-за этого «Деньги сейчас» показывали 96,97 млн вместо
-- настоящих 84,5 млн.
--
-- Двумя шагами, и порядок важен.
--
-- Сначала помечаем исходные строки как исключённые. Загрузчик переносит в
-- payments только строки со статусом не «error» и не «excluded», а связывает
-- их по ключу исходной строки. Удали платёж, оставив строку, — и следующая же
-- загрузка вернёт его обратно, потому что конфликта по ключу больше нет.
-- Помечаем, а не удаляем: исходная запись остаётся историей, видно, что было
-- в файле и почему не взято.
--
-- Потом удаляем сами платежи. Проверено перед удалением: ни на одном из них
-- нет привязки к сделке, поэтому ни одна связь «платёж → сделка» не рвётся.
--
-- Сделки не трогаем: их удаление — отдельное решение по каждой.

begin;

update staging_payment_operations s
set validation_status = 'excluded',
    updated_at = now()
where s.validation_status not in ('error', 'excluded')
  and (
      s.likely_internal_transfer
      or (
          s.source_sheet = 'ПоступленияН'
          and coalesce(s.category, '') <> 'Основная деятельность'
      )
  );

delete from payments p
where p.source = 'payment_battery'
  and (
      p.is_internal_transfer
      or (
          p.source_sheet = 'ПоступленияН'
          and p.operation_type <> 'Основная деятельность'
      )
  )
  and not exists (
      -- страховка: платёж с привязкой к сделке не удаляем ни при каких
      -- условиях, даже если он попал под правило
      select 1 from payment_allocations a where a.payment_id = p.id
  );

commit;
