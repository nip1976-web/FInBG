-- Разрешает сделке не иметь даты открытия.
--
-- Пока в базу попадали только оплаченные в 2026 году, дата всегда находилась:
-- не дата документа, так дата оплаты. С расширением отбора — незакрытые сделки
-- берём независимо от даты оплаты — появились строки, где нет ни той, ни другой.
-- Такая одна: Приангарский, счёт 1708 на 105 300 ₽, весь остаток не оплачен.
--
-- Подставлять выдуманную дату нельзя: она попадёт в отчёты и будет выглядеть
-- как факт. Честнее оставить пусто — мы действительно не знаем, когда документ
-- выписан.

alter table deals alter column opened_on drop not null;

comment on column deals.opened_on is
    'Дата документа, а если её нет — дата оплаты. Пусто, когда в файле нет ни той, ни другой';
