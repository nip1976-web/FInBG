-- Состояние отгрузки у сделки — отдельным полем.
--
-- Николай хотел брать из файла только сделки со состоянием «нет» и «отгружен»:
-- это его рабочий список, незакрытая работа, за которой нужно следить.
-- Закрытых 273 из 306, они внимания не требуют и только загромождают экран.
--
-- Отбирать при загрузке нельзя: по закрытым сделкам деньги пришли, и 250
-- привязанных платежей на 30,5 млн ₽ остались бы без своих сделок. Посчитано
-- до того, как решение было принято.
--
-- Поэтому грузим всё, а отбираем при показе. Разница в том, где стоит фильтр:
-- в загрузке он необратим, то, что не взяли, для системы не существует; в
-- показе он ничего не стоит и меняется одним щелчком.
--
-- Поле вычисляемое, а не заполняемое: значение всегда берётся из того же
-- source_payload, который пишет загрузчик, и разойтись с ним не может.

alter table deals
    add column if not exists shipping_status text
    generated always as (source_payload->>'shippingStatus') stored;

comment on column deals.shipping_status is
    'Состояние отгрузки из файла: закрыт, нет, отгружен. Рабочий список — '
    'это «нет» и «отгружен»';

create index if not exists deals_shipping_status_idx
    on deals (shipping_status);
