-- Место под ИНН плательщика в платежах.
--
-- Николай с августа 2026 вносит ИНН прямо в файл платежей. Это важнее, чем
-- кажется: сейчас ИНН у нас берётся из Bitrix, то есть принадлежит **счёту**.
-- А ИНН в платёжке принадлежит **тому, кто заплатил**. В большинстве случаев
-- это одна фирма, но именно расхождение — платит не тот, на кого выставлен
-- счёт — и стоит замечать. Из счёта такое не увидеть по определению.
--
-- Поле заводим заранее, до того как в файле появится первая заполненная
-- строка: иначе ИНН будет молча теряться при загрузке, и обнаружится это
-- через месяц.
--
-- Пусто для всех прошлых платежей — так и должно быть, до августа его
-- в файле не было.

alter table staging_payment_operations
    add column if not exists payer_tax_id text;

alter table payments
    add column if not exists payer_tax_id text;

comment on column payments.payer_tax_id is
    'ИНН плательщика из выписки. Может не совпадать с ИНН клиента по счёту — '
    'это и есть повод посмотреть глазами';

create index if not exists payments_payer_tax_id_idx
    on payments (payer_tax_id)
    where payer_tax_id is not null;
