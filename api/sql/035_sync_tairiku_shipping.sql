-- Приводит состояние отгрузки сделки Тайрику к тому, что теперь в файле.
--
-- Побочный эффект правила «незакрытые берём всегда». Сделка попадает в базу,
-- пока она в работе. Николай закрыл её в файле 07.08.2026 — и строка перестала
-- проходить отбор: оплата по ней была в 2021 году, в период она не входит.
-- Загрузчик её больше не видит, а в базе осталось прежнее «нет», и в рабочем
-- списке она продолжала висеть.
--
-- Удалять не за что: сделка настоящая, просто закрытая. Записываем то, что
-- говорит файл.
--
-- На будущее: так поведёт себя любая сделка, которая закрывается уже после
-- того, как выпала из периода. Пока их единицы — правим точечно; станет
-- заметно — придётся расширять отбор по дате документа.

update deals d
set source_payload = jsonb_set(
        d.source_payload, '{shippingStatus}', '"закрыт"'::jsonb, true
    ),
    updated_at = now()
where d.source_row = 1026
  and d.source_payload->>'shippingStatus' = 'нет'
  and not exists (select 1 from payment_allocations a where a.deal_id = d.id);
