-- Ручное деление платежа по счетам Bitrix.
--
-- Выгрузка делит платёж сама, когда в назначении названы счета и их суммы
-- складываются в платёж целиком. Этого хватает не всегда:
--
--   * номер написан так, что его не прочесть — «ПО СЧЕТУ 741 ОТ 745В»;
--   * счёт не назван вовсе — Промлес заплатил и за 859, не упомянув его;
--   * доля частичная — из 412 014 ₽ на счёт 1727 пошло 13 140 при счёте
--     16 080, остальное клиент доплатил отдельной платёжкой через неделю.
--
-- Тогда счета и суммы называет человек. Проверка остаётся та же: доли обязаны
-- сложиться в платёж до копейки, иначе выгрузка деление не применит и напишет
-- об этом в отчёт. Описка в сумме молча не пройдёт.
--
-- Таблица отдельная, как и прочие решения человека: заливка её не тронет.

create table if not exists payment_invoice_splits (
    payment_id        bigint         not null references payments (id) on delete cascade,
    bitrix_invoice_id bigint         not null,
    amount_rub        numeric(18, 2) not null check (amount_rub > 0),
    reason            text           not null,
    created_at        timestamptz    not null default now(),
    primary key (payment_id, bitrix_invoice_id)
);

comment on table payment_invoice_splits is
    'Платёж, расписанный по счетам Bitrix рукой человека: доли обязаны сойтись с платежом';

